    @Override
    public void renderToBuffer(PoseStack pose, VertexConsumer buffer, int light, int overlay, float r, float g, float b, float a) {
        MeshLibrary lib = MeshLibrary.get();
        if (lib == null) return;
        renderBone(0, pose, buffer, light, overlay, r, g, b, a * this.alpha, lib);
    }

    private void renderBone(int i, PoseStack pose, VertexConsumer vc, int light, int overlay, float r, float g, float b, float a, MeshLibrary lib) {
        ModelPart part = this.bones[i];
        if (!part.visible) return;
        pose.pushPose();
        part.translateAndRotate(pose);
        lib.draw(this.glowPass ? this.boneNames[i] + "#glow" : this.boneNames[i], pose.last(), vc, light, overlay, r, g, b, a);
        for (int c : this.children[i]) renderBone(c, pose, vc, light, overlay, r, g, b, a, lib);
        pose.popPose();
    }

    // ------------------------------------------------------------------ noise helpers
    private static float hash(int n) {
        n = (n << 13) ^ n;
        return 1.0F - ((n * (n * n * 15731 + 789221) + 1376312589) & 0x7fffffff) / 1073741824.0F;
    }

    /** Mostly zero, with sudden involuntary spikes in [-1, 1]. */
    private static float twitch(float t, int seed, float rate) {
        float x = t * rate;
        int i = Mth.floor(x);
        if (hash(i * 31 + seed * 977) < 0.45F) return 0.0F;
        float f = x - i;
        float pulse = f < 0.12F ? f / 0.12F : Math.max(0.0F, 1.0F - (f - 0.12F) / 0.3F);
        return pulse * hash(i * 17 + seed * 7919);
    }

    private static float smooth(float x) {
        x = Mth.clamp(x, 0.0F, 1.0F);
        return x * x * (3.0F - 2.0F * x);
    }

    private static float easeOut(float x) {
        x = Mth.clamp(x, 0.0F, 1.0F);
        return 1.0F - (1.0F - x) * (1.0F - x) * (1.0F - x);
    }

    // ------------------------------------------------------------------ animation
    @Override
    public void setupAnim(AbominationEntity e, float limbSwing, float limbSwingAmount, float t, float netHeadYaw, float headPitch) {
        this.root.getAllParts().forEach(ModelPart::resetPose);
        for (ModelPart p : this.scaled) {
            p.xScale = 1.0F;
            p.yScale = 1.0F;
            p.zScale = 1.0F;
        }
        this.alpha = 1.0F;
        this.head.xScale = HEAD_SCALE;
        this.head.yScale = HEAD_SCALE;
        this.head.zScale = HEAD_SCALE;

        float pt = t - e.tickCount;
        int anim = e.getAnim();
        float age = e.tickCount - e.animStartTick + pt;
        float sprint = Mth.lerp(pt, e.prevSprintBlend, e.sprintBlend);
        float climb = Mth.lerp(pt, e.prevClimbBlend, e.climbBlend);
        float frozen = Mth.lerp(pt, e.prevFrozenBlend, e.frozenBlend);
        float warp = Mth.lerp(pt, e.prevWarp, e.warpClient);
        float amt = Math.min(1.0F, limbSwingAmount * 1.6F);
        float stalk = e.getPhase() == AbominationEntity.PHASE_STALK ? 1.0F : 0.0F;
        float life = 1.0F - frozen;
        if (anim == AbominationEntity.ANIM_FINISHER && age > 22 && age < 26) life = 0.0F; // dead stillness before impact

        idle(t, life, frozen);
        walk(limbSwing, amt * (1.0F - sprint) * (1.0F - climb), stalk);
        sprint(limbSwing, t, sprint);
        climb(t, climb);

        // head tracking (replaced by some cinematics below)
        float look = (1.0F - sprint * 0.5F) * (anim == AbominationEntity.ANIM_FINISHER ? 0.0F : 1.0F);
        if (anim != AbominationEntity.ANIM_DETECT) {
            this.head.yRot += netHeadYaw * DEG * 0.6F * look;
            this.neck.yRot += netHeadYaw * DEG * 0.4F * look;
            this.head.xRot += headPitch * DEG * 0.6F * look;
        }

        switch (anim) {
            case AbominationEntity.ANIM_DETECT -> detect(age, netHeadYaw);
            case AbominationEntity.ANIM_ATTACK -> swipe(age, (e.getAnimVariant() & 1) == 0);
            case AbominationEntity.ANIM_SLAM -> slam(age);
            case AbominationEntity.ANIM_LEAP -> leap(age);
            case AbominationEntity.ANIM_ROAR -> roar(age, t);
            case AbominationEntity.ANIM_EMERGE -> emerge(age, t);
            case AbominationEntity.ANIM_FINISHER -> finisher(age, t);
            default -> { }
        }

        if (e.hurtTime > 0 && e.deathTime == 0) hurt(e.hurtTime - pt, t);
        if (e.deathTime > 0) death(e.deathTime + pt, t);
        applyWarp(warp, t);
    }

    private void idle(float t, float life, float frozen) {
        float breath = Mth.sin(t * 0.09F);
        this.chest.xRot += breath * 0.03F;
        this.chest.xScale = 1.0F + breath * 0.035F * life;
        this.chest.zScale = 1.0F + breath * 0.035F * life;

        // impossible head tilts and independent jerks
        float bigTilt = smooth((Mth.sin(t * 0.013F) - 0.7F) * 4.0F);
        this.head.zRot += (Mth.sin(t * 0.031F) * 0.35F + twitch(t, 1, 0.11F) * 1.1F + bigTilt * 1.5F) * life;
        this.head.yRot += twitch(t, 2, 0.13F) * 0.5F * life;
        this.neck.zRot += Mth.sin(t * 0.05F) * 0.08F * life;
        this.neck.xRot += twitch(t, 3, 0.09F) * 0.3F * life;

        // eyes roll independently of one another
        for (int i = 0; i < this.eyes.length; i++) {
            ModelPart eye = this.eyes[i];
            eye.yRot += Mth.sin(t * (0.3F + i * 0.07F) + i * 1.7F) * 0.9F;
            eye.xRot += Mth.cos(t * (0.27F + i * 0.05F) + i) * 0.7F;
            eye.x += twitch(t, 10 + i, 0.5F) * 0.25F;
            eye.y += twitch(t, 20 + i, 0.4F) * 0.2F;
            if (twitch(t, 40 + i, 0.06F) > 0.8F) eye.yScale = 0.15F;
        }

        this.jaw.xRot += (0.05F + Math.abs(Mth.sin(t * 0.07F)) * 0.1F + Math.max(0.0F, twitch(t, 4, 0.2F)) * 0.6F) * life;
        this.jaw_inner.z -= Math.max(0.0F, twitch(t, 5, 0.08F)) * 2.5F * life;

        // the external spine writhes on its own rhythm
        for (int i = 0; i < this.spine.length; i++) {
            this.spine[i].xRot += Mth.sin(t * 0.13F - i * 0.7F) * 0.12F * (0.4F + life * 0.6F);
            this.spine[i].yRot += Mth.sin(t * 0.07F + i * 0.9F) * 0.1F * (0.4F + life * 0.6F);
            this.spine[i].zRot += twitch(t, 60 + i, 0.2F) * 0.15F * life;
        }
        for (int i = 0; i < 4; i++) {
            this.tendrilA[i].xRot += Mth.sin(t * 0.08F + i * 0.8F) * 0.2F;
            this.tendrilA[i].zRot += Mth.cos(t * 0.06F + i) * 0.15F;
            this.tendrilB[i].xRot += Mth.sin(t * 0.09F + i * 0.7F + 2.0F) * 0.22F;
            this.tendrilB[i].zRot += Mth.cos(t * 0.05F + i + 1.0F) * 0.18F;
        }
        for (int i = 0; i < 3; i++) {
            this.rFingers[i].xRot += twitch(t, 30 + i, 0.25F) * 0.6F * life;
            this.rClaws[i].xRot += twitch(t, 35 + i, 0.3F) * 0.4F * life;
        }
        for (int i = 0; i < 4; i++) {
            this.lFingers[i].xRot += twitch(t, 50 + i, 0.22F) * 0.6F * life;
            this.lClaws[i].xRot += twitch(t, 55 + i, 0.3F) * 0.4F * life;
        }
        // hanging viscera and torn skin swing and twitch
        for (int i = 0; i < 3; i++) {
            this.guts[i].xRot += Mth.sin(t * 0.07F + i * 1.3F) * 0.18F + twitch(t, 90 + i, 0.15F) * 0.25F;
            this.guts[i].zRot += Mth.cos(t * 0.05F + i) * 0.15F;
            this.flaps[i].xRot += Mth.sin(t * 0.09F + i * 2.1F) * 0.12F;
            this.flaps[i].zRot += Mth.sin(t * 0.06F + i) * 0.08F;
        }
        this.rshoulder.zRot += Mth.sin(t * 0.04F) * 0.05F;
        this.lshoulder.xRot += twitch(t, 70, 0.07F) * 0.45F * life;
        this.lmid.zRot += twitch(t, 71, 0.09F) * 0.3F * life;

        // frozen by your gaze: everything stops except a fine tremble
        float tremble = Mth.sin(t * 3.1F) * 0.012F * frozen;
        this.chest.zRot += tremble;
        this.head.xRot += tremble * 1.5F;
        this.lthigh.zRot += Mth.sin(t * 2.7F) * 0.006F;
    }

    private void walk(float ls, float w, float stalk) {
        if (w > 0.001F) {
            float s = ls * 0.38F;
            this.lthigh.xRot += Mth.cos(s) * 0.75F * w;
            this.rthigh.xRot += Mth.cos(s + PI) * 0.75F * w;
            this.lshin.xRot += Math.max(0.0F, -Mth.sin(s)) * 0.9F * w;
            this.rshin.xRot += Math.max(0.0F, Mth.sin(s)) * 0.9F * w;
            this.hips.yRot += Mth.sin(s) * 0.12F * w;
            this.chest.zRot += Mth.sin(s) * 0.06F * w;
            this.rshoulder.xRot += Mth.cos(s + PI) * 0.25F * w;
            this.lshoulder.xRot += Mth.cos(s) * 0.25F * w;
            this.head.xRot += Mth.sin(s * 2.0F) * 0.05F * w;
            for (ModelPart c : this.rClaws) c.xRot -= 0.4F * w;
            for (ModelPart c : this.lClaws) c.xRot -= 0.4F * w;
        }
        // stalking: lower, more hunched, head thrust forward
        this.chest.xRot += 0.25F * stalk;
        this.head.xRot -= 0.25F * stalk;
        this.neck.xRot -= 0.2F * stalk;
        this.root.y += 2.0F * stalk;
    }

    private void sprint(float ls, float t, float s) {
        if (s < 0.001F) return;
        float g = ls * 0.55F;
        // drop onto all fours: torso horizontal, arms become front legs
        this.hips.xRot += 0.7F * s;
        this.torso.xRot += 0.1F * s;
        this.root.y += 9.0F * s;
        this.neck.xRot -= 1.0F * s;
        this.head.xRot -= 0.3F * s;
        this.rshoulder.xRot += (-0.9F + Mth.cos(g) * 0.7F) * s;
        this.rfore.xRot += (0.3F + Mth.sin(g) * 0.3F) * s;
        this.lshoulder.xRot += (-0.9F + Mth.cos(g + 0.4F) * 0.7F) * s;
        this.lmid.xRot -= 0.2F * s;
        this.lfore.xRot += (0.5F + Mth.sin(g + 0.4F) * 0.3F) * s;
        this.lthigh.xRot += (-0.6F + Mth.cos(g + PI) * 0.8F) * s;
        this.rthigh.xRot += (-0.6F + Mth.cos(g + PI + 0.4F) * 0.8F) * s;
        this.lshin.xRot += (0.9F + Mth.sin(g) * 0.4F) * s;
        this.rshin.xRot += (0.9F + Mth.sin(g + 0.4F) * 0.4F) * s;
        this.chest.yRot += Mth.sin(g) * 0.08F * s;
        for (int i = 0; i < this.spine.length; i++) this.spine[i].xRot += (0.15F + Mth.sin(g - i * 0.5F) * 0.1F) * s;
        for (int i = 0; i < 4; i++) {
            this.tendrilA[i].xRot -= 0.5F * s;
            this.tendrilB[i].xRot -= 0.5F * s;
        }
        this.jaw.xRot += (0.3F + Mth.sin(t * 0.8F) * 0.1F) * s;
    }

    private void climb(float t, float c) {
        if (c < 0.001F) return;
        float k = t * 0.25F;
        // spread-eagled, insect-like crawl up the wall
        this.chest.xRot -= 0.35F * c;
        this.hips.xRot -= 0.2F * c;
        this.rshoulder.xRot += (-2.6F + Mth.sin(k) * 0.5F) * c;
        this.rshoulder.zRot += 0.5F * c;
        this.lshoulder.xRot += (-2.6F + Mth.sin(k + PI) * 0.5F) * c;
        this.lshoulder.zRot -= 0.5F * c;
        this.lthigh.zRot -= 0.5F * c;
        this.rthigh.zRot += 0.5F * c;
        this.lthigh.xRot += (-0.5F + Mth.sin(k + PI) * 0.4F) * c;
        this.rthigh.xRot += (-0.5F + Mth.sin(k) * 0.4F) * c;
        this.head.zRot += (1.1F + twitch(t, 80, 0.4F) * 0.6F) * c;
        for (ModelPart f : this.lFingers) f.xRot -= 0.5F * c;
        for (ModelPart f : this.rFingers) f.xRot -= 0.5F * c;
    }

    private void detect(float age, float netHeadYaw) {
        // body locked; head creaks round in stop-motion steps, tilted, then the jaw starts to open
        float p = Mth.clamp((age - 6.0F) / 24.0F, 0.0F, 1.0F);
        float stepped = Mth.floor(p * 6.0F) / 6.0F;
        this.head.yRot += netHeadYaw * DEG * stepped;
        this.neck.yRot += netHeadYaw * DEG * 0.4F * stepped;
        this.head.zRot += (1.0F - stepped) * 0.9F;
        this.jaw.xRot += stepped * 0.5F;
    }

    private void swipe(float a, boolean leftArm) {
        float wind;
        if (a < 7.0F) wind = smooth(a / 7.0F);
        else if (a < 10.0F) wind = 1.0F - 1.8F * easeOut((a - 7.0F) / 3.0F);
        else wind = -0.8F * (1.0F - Math.min(1.0F, (a - 10.0F) / 10.0F));
        float side = leftArm ? 1.0F : -1.0F;
        ModelPart arm = leftArm ? this.lshoulder : this.rshoulder;
        arm.xRot += wind > 0 ? -2.6F * wind : wind;
        arm.zRot += side * 0.6F * Math.max(0.0F, -wind);
        this.chest.yRot += 0.45F * wind * side;
        this.jaw.xRot += 0.9F * Math.max(0.0F, wind) + (a > 7.0F && a < 12.0F ? 0.6F : 0.0F);
        this.head.xRot -= 0.3F * wind;
        ModelPart[] fingers = leftArm ? this.lFingers : this.rFingers;
        for (ModelPart f : fingers) f.xRot -= 0.6F * wind;
        float lunge = a > 6.0F && a < 12.0F ? Mth.sin((a - 6.0F) / 6.0F * PI) : 0.0F;
        this.root.z -= 4.0F * lunge;
    }

    private void slam(float a) {
        float raise = a < 12.0F ? smooth(a / 12.0F) : 0.0F;
        float down = a >= 12.0F ? Math.max(0.0F, 1.0F - (a - 15.0F) / 15.0F) * easeOut((a - 12.0F) / 3.0F) : 0.0F;
        this.lshoulder.xRot += -2.9F * raise + 0.4F * down;
        this.rshoulder.xRot += -2.9F * raise + 0.4F * down;
        this.lshoulder.zRot -= 0.3F * raise;
        this.rshoulder.zRot += 0.3F * raise;
        this.chest.xRot += -0.4F * raise + 0.6F * down;
        this.head.xRot -= 0.5F * raise;
        this.jaw.xRot += 1.0F * raise + 0.5F * down;
        this.root.y += 3.0F * down;
    }

    private void leap(float a) {
        float p = smooth(a / 4.0F);
        this.lshoulder.xRot -= 1.4F * p;
        this.rshoulder.xRot -= 1.4F * p;
        this.lthigh.xRot += 0.9F * p;
        this.rthigh.xRot += 0.9F * p;
        this.chest.xRot += 0.3F * p;
        this.jaw.xRot += 1.0F * p;
        for (ModelPart f : this.lFingers) f.xRot -= 0.7F * p;
        for (ModelPart f : this.rFingers) f.xRot -= 0.7F * p;
    }

    private void roar(float a, float t) {
        float r = smooth(a / 6.0F);
        this.rshoulder.zRot += 1.2F * r;
        this.lshoulder.zRot -= 1.2F * r;
        this.rshoulder.xRot -= 0.6F * r;
        this.lshoulder.xRot -= 0.6F * r;
        this.head.xRot -= 0.8F * r;
        this.neck.xRot -= 0.5F * r;
        this.jaw.xRot += 1.15F * r;
        this.jaw_inner.z -= 2.5F * r;
        this.chest.xScale *= 1.0F + 0.15F * r;
        this.chest.zScale *= 1.0F + 0.15F * r;
        float shake = Mth.sin(t * 4.0F) * 0.05F * r;
        this.head.zRot += shake;
        this.chest.zRot += shake;
        for (int i = 0; i < 4; i++) {
            this.tendrilA[i].xRot -= 0.8F * r;
            this.tendrilB[i].xRot -= 0.8F * r;
        }
        for (ModelPart f : this.lFingers) f.xRot -= 0.6F * r;
        for (ModelPart f : this.rFingers) f.xRot -= 0.6F * r;
    }

    private void emerge(float a, float t) {
        // clawing up out of the ground, thrashing, then a full roar
        float claw = a < 60.0F ? 1.0F : 1.0F - smooth((a - 60.0F) / 10.0F);
        this.rshoulder.xRot += (-2.7F + Mth.sin(t * 0.5F) * 0.6F) * claw;
        this.lshoulder.xRot += (-2.7F + Mth.sin(t * 0.5F + PI) * 0.6F) * claw;
        this.head.zRot += Mth.sin(t * 0.9F) * 0.6F * claw;
        this.head.xRot -= 0.4F * claw;
        this.jaw.xRot += (0.4F + Math.abs(Mth.sin(t * 0.6F)) * 0.6F) * claw;
        if (a >= 60.0F) roar(a - 60.0F, t);
    }

    private void finisher(float a, float t) {
        // 0-6: lunge and seize the victim with the holding arm
        float seize = smooth(a / 6.0F);
        float release = smooth((a - 62.0F) / 12.0F);
        this.rshoulder.xRot += (-1.25F * seize) * (1.0F - release);
        this.rfore.xRot -= 0.25F * seize * (1.0F - release);
        for (ModelPart f : this.rFingers) f.xRot += 0.8F * seize * (1.0F - release);
        float lunge = a < 8.0F ? Mth.sin(a / 8.0F * PI) : 0.0F;
        this.root.z -= 3.0F * lunge;

        // 4-26: face pushed right up against the victim; the jaw unhinges
        float close = smooth((a - 4.0F) / 18.0F) * (1.0F - smooth((a - 30.0F) / 8.0F));
        this.neck.xRot -= 0.5F * close;
        this.neck.yScale *= 1.0F + 0.3F * close;
        this.head.xRot += 0.35F * close;
        this.jaw.xRot += 1.35F * close;
        this.jaw_inner.z -= 3.0F * close;
        for (int i = 0; i < this.eyes.length; i++) this.eyes[i].yRot += Mth.sin(t * 2.3F + i) * 0.6F * close;

        // 26: the ripping arm snaps forward and closes on the skull
        float grip = smooth((a - 25.0F) / 2.0F);
        // 30-56: tears upward, raising head and spine overhead
        float rip = easeOut((a - 30.0F) / 26.0F);
        float lower = smooth((a - 140.0F) / 10.0F);
        this.lshoulder.xRot += (-1.7F * grip - 1.3F * rip) * (1.0F - lower);
        this.lmid.xRot -= 0.2F * grip * (1.0F - lower);
        this.lfore.xRot += 0.4F * (1.0F - rip) * grip;
        for (ModelPart f : this.lFingers) f.xRot += 0.9F * grip * (1.0F - lower);
        for (ModelPart c : this.lClaws) c.xRot += 0.6F * grip * (1.0F - lower);
        this.chest.xRot -= 0.3F * rip * (1.0F - lower);
        this.chest.yRot -= 0.2F * rip * (1.0F - lower);
        if (a > 26.0F && a < 56.0F) {
            float strain = Mth.sin(t * 2.6F) * 0.04F;
            this.lshoulder.zRot += strain;
            this.chest.zRot += strain;
        }

        // 56+: admires the trophy, head cocked, swaying
        float admire = smooth((a - 56.0F) / 10.0F) * (1.0F - lower);
        this.head.xRot -= 0.45F * admire;
        this.head.zRot += 0.65F * admire;
        this.lshoulder.xRot += Mth.sin(t * 0.15F) * 0.1F * admire;
        this.jaw.xRot += (0.3F + Math.abs(Mth.sin(t * 0.21F)) * 0.4F) * admire;
    }

    private void hurt(float h, float t) {
        float s = h / 10.0F;
        this.chest.xRot -= 0.3F * s;
        this.head.xRot -= 0.5F * s;
        this.head.zRot += Mth.sin(t * 5.0F) * 0.4F * s;
        this.lshoulder.zRot += Mth.sin(t * 4.3F) * 0.4F * s;
        this.rshoulder.zRot += Mth.sin(t * 3.7F + 1.0F) * 0.4F * s;
        this.jaw.xRot += 0.8F * s;
        for (int i = 0; i < this.spine.length; i++) this.spine[i].xRot += Mth.sin(t * 6.0F + i) * 0.3F * s;
    }

    private void death(float d, float t) {
        float c = easeOut(d / 20.0F);
        this.root.y += 14.0F * c;
        this.hips.xRot += 0.9F * c;
        this.chest.xRot += 0.6F * c;
        this.head.zRot += 0.9F * c;
        this.lthigh.xRot -= 1.4F * c;
        this.rthigh.xRot -= 1.3F * c;
        this.lshin.xRot += 1.8F * c;
        this.rshin.xRot += 1.7F * c;
        this.rshoulder.xRot += 0.4F * c;
        this.lshoulder.xRot += 0.5F * c;
        float conv = Math.max(0.0F, 1.0F - d / 70.0F);
        this.chest.zRot += Mth.sin(t * 2.5F) * 0.25F * conv;
        this.head.xRot += Mth.sin(t * 3.1F + 1.0F) * 0.4F * conv;
        this.lshoulder.zRot += Mth.sin(t * 2.2F + 2.0F) * 0.5F * conv;
        this.rshoulder.zRot += Mth.sin(t * 2.9F + 3.0F) * 0.5F * conv;
        this.jaw.xRot += 0.6F + Mth.sin(t * 1.7F) * 0.4F * conv;
        for (int i = 0; i < this.spine.length; i++) this.spine[i].xRot += Mth.sin(t * 2.0F + i) * 0.35F * conv;
        this.alpha = 1.0F - Mth.clamp((d - 30.0F) / 40.0F, 0.0F, 1.0F);
    }

    private void applyWarp(float w, float t) {
        if (w < 0.001F) return;
        this.neck.yScale *= 1.0F + w * 0.9F;
        this.lshoulder.yScale *= 1.0F + w * 0.35F;
        this.lfore.yScale *= 1.0F + w * 0.5F;
        this.rfore.yScale *= 1.0F + w * 0.45F;
        this.head.xScale *= 1.0F + w * 0.25F * Mth.sin(t * 0.9F);
        this.head.zScale *= 1.0F + w * 0.3F;
        this.jaw.zScale *= 1.0F + w * 0.4F;
        for (int i = 0; i < this.eyes.length; i++) {
            float s = 1.0F + w * (0.6F + 0.5F * Mth.sin(t * 0.7F + i * 2.0F));
            this.eyes[i].xScale *= s;
            this.eyes[i].yScale *= s;
            this.eyes[i].zScale *= s;
        }
        this.spine_1.yScale *= 1.0F + w * 0.3F;
        this.spine_3.yScale *= 1.0F + w * 0.3F;
        this.spine_5.yScale *= 1.0F + w * 0.3F;
        this.spine_7.yScale *= 1.0F + w * 0.3F;
        this.chest.xScale *= 1.0F + w * 0.08F * Mth.sin(t * 1.3F);
    }
