"""Renders 虎杖悠仁 (Itadori Yuji) as a bitmap for the World Ender's signature: the Final Judgment carves it into the
floor of its crater. Writes src/main/java/com/yuji/common/NameGlyph.java (rows of '#' and '.').

    python3 tools/gen_name_glyph.py
"""
import os
from PIL import Image, ImageDraw, ImageFont

TEXT = "虎杖悠仁"   # 虎杖悠仁
CELL = 40                           # pixels per character
FONT = "/usr/share/fonts/opentype/noto/NotoSansCJK-Black.ttc"
font = ImageFont.truetype(FONT, int(CELL * 0.92), index=0)   # face 0: Noto Sans CJK JP
gap = 4
W = len(TEXT) * CELL + (len(TEXT) - 1) * gap
img = Image.new("L", (W, CELL), 0)
d = ImageDraw.Draw(img)
for i, ch in enumerate(TEXT):
    x0 = i * (CELL + gap)
    box = d.textbbox((0, 0), ch, font=font)
    w, h = box[2] - box[0], box[3] - box[1]
    d.text((x0 + (CELL - w) / 2 - box[0], (CELL - h) / 2 - box[1]), ch, font=font, fill=255)
rows = ["".join("#" if img.getpixel((x, y)) > 110 else "." for x in range(W)) for y in range(CELL)]
for r in rows[::2]:
    print(r)
out = os.path.join(os.path.dirname(__file__), "..", "src", "main", "java", "com", "yuji", "common", "NameGlyph.java")
with open(out, "w", encoding="utf-8") as f:
    f.write("package com.yuji.common;\n\n")
    f.write("/** 虎杖悠仁 as a bitmap ('#' = stroke), carved into the World Ender's crater. Generated by tools/gen_name_glyph.py. */\n")
    f.write("public final class NameGlyph {\n    private NameGlyph() {}\n\n")
    f.write(f"    public static final int W = {W}, H = {CELL};\n\n    public static final String[] ROWS = {{\n")
    for r in rows:
        f.write(f'            "{r}",\n')
    f.write("    };\n\n    /** Is (x, y) inside a stroke? x right, y down, in bitmap pixels. */\n")
    f.write("    public static boolean ink(int x, int y) {\n        return x >= 0 && y >= 0 && x < W && y < H && ROWS[y].charAt(x) == '#';\n    }\n}\n")
print("wrote", out, W, "x", CELL)
